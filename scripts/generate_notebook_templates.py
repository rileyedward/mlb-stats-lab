"""Generate the four notebook template .ipynb files.

Run once (or any time the template skeleton needs to change):

    uv run python scripts/generate_notebook_templates.py
"""

from __future__ import annotations

from pathlib import Path

import nbformat as nbf

OUT_DIR = Path(__file__).resolve().parents[1] / "reports" / "templates" / "notebooks"


def md(text: str) -> nbf.NotebookNode:
    return nbf.v4.new_markdown_cell(text)


def code(source: str, tags: list[str] | None = None) -> nbf.NotebookNode:
    cell = nbf.v4.new_code_cell(source)
    if tags:
        cell.metadata["tags"] = tags
    return cell


def make_notebook(cells: list[nbf.NotebookNode]) -> nbf.NotebookNode:
    nb = nbf.v4.new_notebook()
    nb.cells = cells
    nb.metadata["kernelspec"] = {
        "display_name": "MLB Stats Lab",
        "language": "python",
        "name": "mlb-stats-lab",
    }
    nb.metadata["language_info"] = {"name": "python"}
    return nb


def batter_profile_nb() -> nbf.NotebookNode:
    cells = [
        md("# Batter Profile\n\n*Single-hitter deep dive — generated by `statslab new-notebook batter-profile`.*"),
        code(
            "# parameters\nplayer = \"Aaron Judge\"\nseason = None\nstart_date = None\nend_date = None\nrecent_form_pas = 25\n",
            tags=["parameters"],
        ),
        code(
            "from IPython.display import Markdown, display\n"
            "from mlb_stats_lab.data import current_season, season_range, get_statcast_batter, player_name\n"
            "from mlb_stats_lab.batting import batting_line, plate_discipline, contact_quality, performance_by_pitch_type, rolling_batting_line\n"
            "from mlb_stats_lab.batting.splits import splits as batting_splits\n"
            "from mlb_stats_lab.viz import (spray_chart, zone_heatmap, zone_grid, ev_la_scatter, splits_bar_chart, rolling_metric_line)\n"
            "\n"
            "season = season or current_season()\n"
            "if start_date is None or end_date is None:\n"
            "    s, e = season_range(season)\n"
            "    start_date = start_date or s\n"
            "    end_date = end_date or e\n"
            "display(Markdown(f\"# Batter Profile — {player}\\n*{season} season · {start_date} → {end_date}*\"))\n",
            tags=["setup"],
        ),
        code(
            "df = get_statcast_batter(player, start=start_date, end=end_date)\n"
            "print(f'Loaded {len(df)} pitches for {player}.')\n",
            tags=["load"],
        ),
        md("## §1 Season Line"),
        code(
            "line = batting_line(df)\n"
            "disc = plate_discipline(df)\n"
            "contact = contact_quality(df)\n"
            "display(line.to_frame('value'))\n"
            "display(disc.to_frame('value'))\n"
            "display(contact.to_frame('value'))\n",
            tags=["section"],
        ),
        md("## §2 Spray Chart"),
        code("spray_chart(df, title=f'{player} — Batted Balls')\n", tags=["section"]),
        md("## §3 Zone Profile"),
        code(
            "zone_heatmap(df, metric='density', title='Pitches Seen')\n",
            tags=["section"],
        ),
        code("zone_heatmap(df, metric='swing_rate', title='Swing Rate')\n", tags=["section"]),
        code("zone_grid(df, metric='xwoba', bins=3, title='xwOBA by Zone')\n", tags=["section"]),
        md("## §4 Contact Profile"),
        code("ev_la_scatter(df, color_by='outcome', overlay_barrel_zone=True, title='EV vs LA')\n", tags=["section"]),
        md("## §5 Splits"),
        code(
            "for axis, title in [('vs_hand','vs Hand'),('home_away','Home/Away'),('month','Month')]:\n"
            "    s = batting_splits(df, axis=axis)\n"
            "    display(s)\n"
            "    splits_bar_chart(s, metric='wOBA', title=title)\n",
            tags=["section"],
        ),
        md("## §6 Performance by Pitch Type"),
        code("display(performance_by_pitch_type(df))\n", tags=["section"]),
        md("## §7 Recent Form"),
        code(
            "rolling = rolling_batting_line(df, window=recent_form_pas, over='PA')\n"
            "rolling_metric_line(rolling, metric='wOBA', league_average=0.320, title='Rolling wOBA')\n",
            tags=["section"],
        ),
        md("## §8 Takeaways"),
        code(
            "from mlb_stats_lab.reports.summary import batter_bullets\n"
            "display(Markdown('\\n'.join(batter_bullets(line, disc, contact))))\n",
            tags=["summary"],
        ),
        md("## §9 Export to PDF (optional)"),
        code(
            "# Uncomment to render a PDF:\n"
            "# from mlb_stats_lab.reports import render_report, build_batter_profile_context\n"
            "# ctx = build_batter_profile_context({'player': player, 'season': season, 'start_date': start_date, 'end_date': end_date, 'recent_form_pas': recent_form_pas})\n"
            "# render_report('batter-profile', ctx, f'{player.replace(\" \", \"_\")}__{end_date}.pdf')\n",
            tags=["section", "hidden"],
        ),
    ]
    return make_notebook(cells)


