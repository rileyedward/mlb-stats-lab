def series_matchup_nb() -> nbf.NotebookNode:
    cells = [
        md("# Series Matchup\n\n*Two-team in-depth comparison.*"),
        code(
            "# parameters\nteam_a = \"SEA\"\nteam_b = \"LAD\"\nseason = None\nstart_date = None\nend_date = None\nrecent_form_games = 10\n",
            tags=["parameters"],
        ),
        code(
            "from IPython.display import Markdown, display\n"
            "from mlb_stats_lab.data import current_season, season_range, get_statcast_for_team\n"
            "from mlb_stats_lab.batting import batting_line\n"
            "from mlb_stats_lab.batting.splits import splits as batting_splits\n"
            "from mlb_stats_lab.pitching import pitching_line, arsenal_summary\n"
            "from mlb_stats_lab.viz import splits_bar_chart, pitch_usage_bar, velocity_distribution\n"
            "\n"
            "season = season or current_season()\n"
            "if start_date is None or end_date is None:\n"
            "    s, e = season_range(season)\n"
            "    start_date = start_date or s\n"
            "    end_date = end_date or e\n"
            "display(Markdown(f'# Series Matchup — {team_a} vs {team_b}\\n*{season} · {start_date} → {end_date}*'))\n",
            tags=["setup"],
        ),
        code(
            "a_bat = get_statcast_for_team(team_a, start=start_date, end=end_date, side='batting')\n"
            "a_pit = get_statcast_for_team(team_a, start=start_date, end=end_date, side='pitching')\n"
            "b_bat = get_statcast_for_team(team_b, start=start_date, end=end_date, side='batting')\n"
            "b_pit = get_statcast_for_team(team_b, start=start_date, end=end_date, side='pitching')\n"
            "print(f'{team_a}: {len(a_bat)} bat / {len(a_pit)} pit;  {team_b}: {len(b_bat)} bat / {len(b_pit)} pit')\n",
            tags=["load"],
        ),
        md("## §1 Offense Compare"),
        code(
            "import pandas as pd\n"
            "rows = []\n"
            "for label, sub in ((team_a, a_bat), (team_b, b_bat)):\n"
            "    rows.append(batting_line(sub).rename(label))\n"
            "display(pd.concat(rows, axis=1))\n",
            tags=["section"],
        ),
        code("splits_bar_chart(batting_splits(a_bat, axis='vs_hand'), metric='wOBA', title=f'{team_a} vs Hand')\n", tags=["section"]),
        code("splits_bar_chart(batting_splits(b_bat, axis='vs_hand'), metric='wOBA', title=f'{team_b} vs Hand')\n", tags=["section"]),
        md("## §2 Pitching Compare"),
        code(
            "rows = []\n"
            "for label, sub in ((team_a, a_pit), (team_b, b_pit)):\n"
            "    rows.append(pitching_line(sub).rename(label))\n"
            "display(pd.concat(rows, axis=1))\n",
            tags=["section"],
        ),
        code("pitch_usage_bar(a_pit, title=f'{team_a} Staff Usage')\n", tags=["section"]),
        code("pitch_usage_bar(b_pit, title=f'{team_b} Staff Usage')\n", tags=["section"]),
        code("velocity_distribution(a_pit, kind='kde', title=f'{team_a} Velo')\n", tags=["section"]),
        code("velocity_distribution(b_pit, kind='kde', title=f'{team_b} Velo')\n", tags=["section"]),
        md("## §3 Takeaways"),
        code(
            "summary = [\n"
            "    f'→ {team_a} wOBA {batting_line(a_bat).get(\"wOBA\", 0):.3f} vs {team_b} wOBA {batting_line(b_bat).get(\"wOBA\", 0):.3f}.',\n"
            "    f'→ {team_a} staff K-BB% {pitching_line(a_pit).get(\"K-BB%\", 0):.1%} vs {team_b} staff K-BB% {pitching_line(b_pit).get(\"K-BB%\", 0):.1%}.',\n"
            "]\n"
            "display(Markdown('\\n'.join(summary)))\n",
            tags=["summary"],
        ),
    ]
    return make_notebook(cells)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    builders = {
        "batter-profile": batter_profile_nb,
        "pitcher-profile": pitcher_profile_nb,
        "team-season-snapshot": team_snapshot_nb,
        "series-matchup": series_matchup_nb,
    }
    for name, fn in builders.items():
        nb = fn()
        path = OUT_DIR / f"{name}.ipynb"
        with path.open("w") as f:
            nbf.write(nb, f)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
